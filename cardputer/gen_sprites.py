NIVEL = {" ": 0, ".": 1, ":": 2, "#": 3}


def main():
    nomes = sorted(SPRITES)
    with open("main/ui/sprites.c", "w") as f:
        f.write("// GERADO POR tools/gen_sprites.py - NAO EDITAR A MAO\n")
        f.write('#include "sprites.h"\n\n')
        f.write("const uint8_t sprites[SPR_N][SPR_BYTES] = {\n")
        for nome in nomes:
            linhas = SPRITES[nome]
            if len(linhas) != 8:
                raise SystemExit(f"{nome}: precisa de 8 linhas")
            if any(len(l) != 8 for l in linhas):
                raise SystemExit(f"{nome}: toda linha precisa de 8 colunas")
            f.write(f"    {{  // {nome}\n        ")
            for l in linhas:
                b = 0
                for c in l:
                    b = (b << 2) | NIVEL.get(c, 0)
                f.write(f"0x{(b >> 8) & 0xFF:02X},0x{b & 0xFF:02X}, ")
            f.write("\n    },\n")
        f.write("};\n")

    with open("main/ui/sprites.h", "w") as f:
        f.write("// GERADO POR tools/gen_sprites.py - NAO EDITAR A MAO\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("#define SPR_W 8\n#define SPR_H 8\n#define SPR_BYTES 16\n\n")
        f.write("enum {\n")
        for i, nome in enumerate(nomes):
            f.write(f"    SPR_{nome.upper()},\n")
        f.write("    SPR_N\n};\n\n")
        f.write("extern const uint8_t sprites[SPR_N][SPR_BYTES];\n")
    print(f"  {len(nomes)} sprites")


if __name__ == "__main__":
    main()
